"""Measure reconciliation recall, precision and classification accuracy on planted breaks.

Writes ``docs/recon-report.md``. Every configuration writes the synthetic statement in the bank's
format and parses it back, so parsing is part of what is measured.
"""

from __future__ import annotations

import argparse
import platform
import time
from collections import defaultdict
from datetime import date
from decimal import Decimal
from pathlib import Path

from services.recon.engine import reconcile
from services.recon.formats import FORMATS, parse_statement, write_statement
from services.recon.generator import DEFAULT_PLANTS, evaluate, synthetic_day


def pct(bps: int) -> str:
    return f"{Decimal(bps) / 100:.2f}%"


def run_case(
    transactions: int, seed: int, fmt: str, hard: bool, next_day: bool, scale: int = 1
) -> tuple[object, dict[str, int]]:
    plants = {k: v * scale for k, v in DEFAULT_PLANTS.items()}
    started = time.perf_counter()
    day = synthetic_day(transactions, seed, date(2026, 9, 29), style=fmt, plants=plants, hard=hard)
    generated = time.perf_counter()
    raw = write_statement(day.bank_today, fmt)
    parsed, issues = parse_statement(raw, fmt)
    parsed_at = time.perf_counter()
    assert not issues, issues[:3]
    following = None
    if next_day and day.bank_next_day:
        following, _ = parse_statement(write_statement(day.bank_next_day, fmt), fmt)
    result = reconcile(
        day.ledger,
        day.switch,
        parsed,
        business_date="2026-09-29",
        source=fmt,
        day_end=day.day_end,
        next_day_bank=following if next_day else None,
    )
    finished = time.perf_counter()
    timings = {
        "lines": len(parsed),
        "bytes": len(raw),
        "generate_ms": int((generated - started) * 1000),
        "parse_ms": int((parsed_at - generated) * 1000),
        "reconcile_ms": int((finished - parsed_at) * 1000),
    }
    return evaluate(result, day.planted), timings


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seeds", type=int, default=10)
    parser.add_argument("--transactions", type=int, default=20_000)
    parser.add_argument("--scale-rows", type=int, default=1_000_000)
    parser.add_argument("--output", default="docs/recon-report.md")
    args = parser.parse_args()

    rows = []
    per_type: dict[str, list[int]] = defaultdict(lambda: [0, 0, 0])
    totals: defaultdict[str, int] = defaultdict(int)
    for fmt in FORMATS:
        for hard in (False, True):
            for next_day in (True, False):
                agg: defaultdict[str, int] = defaultdict(int)
                for seed in range(args.seeds):
                    ev, _ = run_case(args.transactions, seed, fmt, hard, next_day, scale=4)
                    agg["planted"] += ev.planted  # type: ignore[attr-defined]
                    agg["detected"] += ev.detected  # type: ignore[attr-defined]
                    agg["correct"] += ev.correctly_classified  # type: ignore[attr-defined]
                    agg["reported"] += ev.breaks_reported  # type: ignore[attr-defined]
                    agg["false"] += ev.false_breaks  # type: ignore[attr-defined]
                    for kind, (p, d, c) in ev.by_type.items():  # type: ignore[attr-defined]
                        per_type[kind][0] += p
                        per_type[kind][1] += d
                        per_type[kind][2] += c
                for key, value in agg.items():
                    totals[key] += value
                rows.append((fmt, hard, next_day, agg))

    scale = []
    for n in (100_000, args.scale_rows):
        _, timing = run_case(n, 99, "json_offset", True, True)
        scale.append((n, timing))

    def bps(num: int, den: int) -> int:
        return 10_000 if den == 0 else num * 10_000 // den

    lines = [
        "# Reconciliation report",
        "",
        "Generated by `uv run python -m scripts.recon_eval` "
        f"on {platform.system()} {platform.machine()}, Python {platform.python_version()}.",
        "",
        "## Method",
        "",
        "`services/recon/generator.py` builds a consistent business day (ledger nostro postings, "
        "switch log, bank statement), then plants labelled breaks on the bank side: missing at "
        "bank, missing internally, amount mismatch, duplicate, status mismatch, timing difference "
        "(moved to the next day's statement), bank fee/GST deduction and an unattributable line. "
        "Each case writes the statement in the bank's format and parses it back before "
        "reconciling. **Hard** mode (bank C style) also removes the merchant reference from 5% of "
        "UPI lines *before* planting, so breaks also land on lines that can only be matched "
        "fuzzily. Cases with and without the next day's statement are both measured.",
        "",
        "Recall = planted breaks detected / planted. Precision = reported breaks that correspond "
        "to a planted break / reported. Classification accuracy = detected breaks with the right "
        "type / detected.",
        "",
        f"## Results ({args.seeds} seeds x {args.transactions:,} transactions per case)",
        "",
        "| Format | Hard | Next-day file | Planted | Recall | Precision | Classification |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: |",
    ]
    for fmt, hard, next_day, agg in rows:
        lines.append(
            f"| `{fmt}` | {'yes' if hard else 'no'} | {'yes' if next_day else 'no'} | "
            f"{agg['planted']:,} | {pct(bps(agg['detected'], agg['planted']))} | "
            f"{pct(bps(agg['reported'] - agg['false'], agg['reported']))} | "
            f"{pct(bps(agg['correct'], agg['detected']))} |"
        )
    lines += [
        f"| **All** | | | **{totals['planted']:,}** | "
        f"**{pct(bps(totals['detected'], totals['planted']))}** | "
        f"**{pct(bps(totals['reported'] - totals['false'], totals['reported']))}** | "
        f"**{pct(bps(totals['correct'], totals['detected']))}** |",
        "",
        "### By break type (all cases)",
        "",
        "| Break type | Planted | Detected | Correctly classified |",
        "| --- | ---: | ---: | ---: |",
    ]
    for kind, (p, d, c) in sorted(per_type.items()):
        lines.append(f"| {kind} | {p:,} | {d:,} | {c:,} |")
    lines += [
        "",
        "## Scale (bank C JSON, hard mode, single process)",
        "",
        "| Transactions | Statement lines | Statement size | Parse | Reconcile |",
        "| ---: | ---: | ---: | ---: | ---: |",
    ]
    for n, timing in scale:
        lines.append(
            f"| {n:,} | {timing['lines']:,} | {timing['bytes'] // 1_000_000} MB | "
            f"{Decimal(timing['parse_ms']) / 1000:.1f} s | "
            f"{Decimal(timing['reconcile_ms']) / 1000:.1f} s |"
        )
    lines += [
        "",
        "The engine is pure Python with hash-indexed matching (linear in lines). Database "
        "persistence of matches and breaks is measured separately in the load-test report.",
        "",
        "## Iteration history",
        "",
        "- First hard-mode run (10 seeds x 20,000): recall 100%, but 40 of 4,320 planted breaks "
        "were misclassified and 24 false breaks were reported. Amount mismatches on lines "
        "without a reference produced an `unknown` bank line plus `missing_at_bank`; timing "
        "differences on such lines were reported as `missing_at_bank`.",
        "- Fix: a second fuzzy stage pairs a reference-less line to a unique record with the "
        "same payer VPA and time window when amounts differ, and next-day carry-over also "
        "matches reference-less lines by kind, amount and VPA.",
        "- Integration run on real services found that the fixed-width writer silently "
        "truncated 41-character simulator references to 24 characters, hiding duplicates. The "
        "writer now refuses to truncate and the simulator emits 16-character UTRs.",
        "",
        "## Limits",
        "",
        "- The generator and engine were written by the same team; the hard mode and the "
        "real-service integration test (`tests/integration/test_reconciliation.py`) exist to "
        "reduce that bias, but results on real bank files would be lower.",
        "- Scope is the platform nostro: UPI transfers, refunds and payouts. Card acquirer "
        "settlements and chargebacks are not reconciled.",
        "- Exact ties in fuzzy matching (same amount, VPA and time distance) are reported as "
        "`unknown` rather than guessed.",
    ]
    Path(args.output).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[14 : 14 + len(rows) + 4]))


if __name__ == "__main__":
    main()
